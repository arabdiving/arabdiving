(async () => {
  try {
    if (!process.env.MONGO_URI) {
      throw new Error("MONGO_URI is not set. Configure backend/.env first.");
    }
    console.log("Connecting to MongoDB...");
    await mongoose.connect(process.env.MONGO_URI);
    console.log("✅ Connected");

    let created = 0, updated = 0;
    for (const c of courses) {
      const result = await Course.updateOne({ title: c.title }, { $set: c }, { upsert: true });
      if (result.upsertedCount) created += 1;
      else if (result.matchedCount) updated += 1;
    }
    console.log(`✅ Courses seeded: ${created} created, ${updated} updated.`);
    console.log("⚠️  الأسعار مصفّرة — حدّدها الآن من لوحة التحكم → الدورات.");
  } catch (e) {
    console.error("❌", e.message);
  } finally {
    await mongoose.disconnect();
  }
})();
